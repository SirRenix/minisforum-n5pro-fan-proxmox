// Command genresults generates hwstatus/results.tsv from the hardware status
// table in befunde/RESULTS.md (the only source of the hardware status).
//
//	go run ./internal/genresults <RESULTS.md> <results.tsv>
//
// It runs through `go generate ./...` in the hwstatus package. The table sits
// between "<!-- hwstatus:begin -->" and "<!-- hwstatus:end -->" and has 8
// columns: product | board | bios | ec | status | origin | date | note.
// Backticks are stripped, cells trimmed. A row with another column count, an
// unknown status, or validated/tested with an origin other than "eigen" fails
// the run; nothing is written then. The output is deterministic (no build
// date): "generated" is the newest date of the table rows, so CI can check
// with `git diff --exit-code` that the committed file is current.
// "source-table-sha256" covers the table only (see package tablesum), so a
// prose change elsewhere in RESULTS.md does not make results.tsv stale.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"os"
	"regexp"
	"strings"

	"github.com/SirRenix/minisforum-n5pro-fan-proxmox/go/n5/hwstatus/internal/tablesum"
)

var (
	statusRe = regexp.MustCompile(`^(validated|tested|experimental|unknown)$`)
	dateRe   = regexp.MustCompile(`^\d{4}-\d{2}-\d{2}$`)
	dashRe   = regexp.MustCompile(`^-+$`)
)

// Generate renders results.tsv from the content of RESULTS.md.
func Generate(src []byte) (string, error) {
	sum, err := tablesum.Sum(src)
	if err != nil {
		return "", err
	}
	var rows []string
	var errs []string
	on, done := false, false
	newest := ""
	sc := bufio.NewScanner(bytes.NewReader(src))
	n := 0
	for sc.Scan() {
		n++
		line := strings.TrimRight(sc.Text(), "\r")
		switch {
		case strings.Contains(line, "<!-- hwstatus:begin -->"):
			on = true
			continue
		case strings.Contains(line, "<!-- hwstatus:end -->"):
			on, done = false, true
			continue
		}
		if !on || strings.TrimSpace(line) == "" {
			continue
		}
		l := strings.ReplaceAll(line, "`", "")
		l = strings.TrimSpace(l)
		l = strings.TrimPrefix(l, "|")
		l = strings.TrimSuffix(l, "|")
		c := strings.Split(l, "|")
		if len(c) != 8 {
			errs = append(errs, fmt.Sprintf("RESULTS.md:%d: %d columns, want 8", n, len(c)))
			continue
		}
		for i := range c {
			c[i] = strings.TrimSpace(strings.ReplaceAll(c[i], "\t", " "))
		}
		if c[0] == "Produkt" || dashRe.MatchString(c[0]) {
			continue
		}
		if !statusRe.MatchString(c[4]) {
			errs = append(errs, fmt.Sprintf("RESULTS.md:%d: unknown status %s", n, c[4]))
			continue
		}
		if (c[4] == "validated" || c[4] == "tested") && c[5] != "eigen" {
			errs = append(errs, fmt.Sprintf("RESULTS.md:%d: status %s needs origin eigen, not %s", n, c[4], c[5]))
			continue
		}
		if dateRe.MatchString(c[6]) && c[6] > newest {
			newest = c[6]
		}
		rows = append(rows, strings.Join(c, "\t"))
	}
	if err := sc.Err(); err != nil {
		return "", err
	}
	if !done {
		errs = append(errs, "RESULTS.md: hwstatus markers not found")
	}
	if len(errs) > 0 {
		return "", fmt.Errorf("%s", strings.Join(errs, "\n"))
	}
	if len(rows) == 0 {
		return "", fmt.Errorf("RESULTS.md: empty hwstatus table")
	}
	if newest == "" {
		return "", fmt.Errorf("RESULTS.md: no row carries a date (YYYY-MM-DD)")
	}
	var b strings.Builder
	b.WriteString("# Generated by go generate (go/n5/hwstatus/internal/genresults) -- do not edit; edit befunde/RESULTS.md and re-run.\n")
	b.WriteString("# source: befunde/RESULTS.md (github.com/SirRenix/minisforum-n5pro-fan-proxmox)\n")
	fmt.Fprintf(&b, "# source-table-sha256: %s\n", sum)
	fmt.Fprintf(&b, "# generated: %s\n", newest)
	b.WriteString("# columns: product\tboard\tbios\tec\tstatus\torigin\tdate\tnote\n")
	for _, r := range rows {
		b.WriteString(r + "\n")
	}
	return b.String(), nil
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: genresults <RESULTS.md> <results.tsv>")
		os.Exit(2)
	}
	src, err := os.ReadFile(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	out, err := Generate(src)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	tmp := os.Args[2] + ".tmp"
	if err := os.WriteFile(tmp, []byte(out), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.Rename(tmp, os.Args[2]); err != nil {
		os.Remove(tmp)
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
